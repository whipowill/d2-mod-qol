#!/usr/bin/env python3
"""Generate src/tables.h (belt code -> number of belt slots) from the game's own Armor.txt + Belts.txt.

Run after the game/mod data changes (e.g. each PD2 season):   python3 -I tools/gen_tables.py
Paths (GAME_DIR, GAME_MPQS, MPQX_DIR) come from local.conf; the MPQ reader is mpqx.py.
"""
import os, sys

def load_conf():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "local.conf")
    if not os.path.exists(path):
        sys.exit("missing local.conf - copy local.conf.example to local.conf and set GAME_DIR / GAME_MPQS / MPQX_DIR")
    conf = {}
    for line in open(path):
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            conf[k.strip()] = os.path.expanduser(v.strip())
    return conf

CONF = load_conf()
sys.path.insert(0, CONF["MPQX_DIR"])
from mpqx import MPQ
import mpqx

# Stock Blizzard archives (d2data.mpq etc.) compress sectors with PKWARE implode (mask 0x08), which the shared
# reader doesn't handle on its own; add it here.
_orig_dec = MPQ._dec
def _dec(self, d, size):
    if d and d[0] == 0x08:
        return mpqx.explode(d[1:])
    return _orig_dec(self, d, size)
MPQ._dec = _dec

GAME = CONF["GAME_DIR"]
MPQS = [m.strip() for m in CONF.get("GAME_MPQS", "d2data.mpq").split(",") if m.strip()]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "tables.h")

class Archives:
    """Several MPQs searched in priority order (first listed wins), e.g. patch_d2.mpq before d2data.mpq."""
    def __init__(self, paths):
        self.mpqs = [MPQ(p) for p in paths]
    def read(self, name):
        for m in self.mpqs:
            data = m.read(name)
            if data is not None:
                return data
        sys.exit("%s not found in any of: %s" % (name, ", ".join(MPQS)))

def table(mpq, name):
    raw = mpq.read("data\\global\\excel\\" + name).decode("latin1").replace("\r", "")
    rows = [l.split("\t") for l in raw.split("\n") if l]
    return rows[0], rows[1:]

mpq = Archives([os.path.join(GAME, m) for m in MPQS])
bh, belts = table(mpq, "Belts.txt")
slots = {i: int(r[bh.index("numboxes")]) for i, r in enumerate(belts) if r[1:2] and r[1].isdigit()}
ah, armor = table(mpq, "Armor.txt")
ci, bi, ti = ah.index("code"), ah.index("belt"), ah.index("type")

# Every item type that is a kind of "belt" (follows Equiv1/Equiv2 chains in ItemTypes.txt), so mod sub-types
# like "bels" (Troll Belt [S]) are covered too.
ih, itypes = table(mpq, "ItemTypes.txt")
tcol, e1, e2 = ih.index("Code"), ih.index("Equiv1"), ih.index("Equiv2")
parents = {r[tcol]: [x for x in (r[e1], r[e2]) if x] for r in itypes if len(r) > e2}
def is_belt(t, seen=()):
    return t == "belt" or any(is_belt(p, seen + (t,)) for p in parents.get(t, []) if p not in seen)
belt_types = {t for t in parents if is_belt(t)}
print("belt item types:", sorted(belt_types))
out = []
for r in armor:
    if len(r) > bi and r[ti] in belt_types and r[bi].isdigit() and int(r[bi]) in slots:
        out.append((r[ci], slots[int(r[bi])]))
with open(OUT, "w") as f:
    f.write("// GENERATED by tools/gen_tables.py - do not edit.\n"
            "// belt item code -> number of belt slots (from the game's Armor.txt + Belts.txt)\n"
            "static const struct { const char *code; int slots; } BELT_TABLE[] = {\n")
    for c, n in out:
        f.write('    {"%s", %d},\n' % (c, n))
    f.write("    {0, 0}\n};\n")
print("wrote", os.path.normpath(OUT), len(out), "belts")
