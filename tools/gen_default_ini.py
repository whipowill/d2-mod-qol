#!/usr/bin/env python3
"""Generates src/default_ini.h (the ini qol.dll writes when qol.ini is missing) from the template src/qoltweaks.ini, so the two can never differ."""
import os
here = os.path.dirname(os.path.abspath(__file__)); src = os.path.join(here, '..', 'src')
t = open(os.path.join(src, 'qoltweaks.ini'), encoding='latin1', newline='').read().replace('\r\n', '\n').replace('\n', '\r\n')
lines = t.split('\r\n')
if lines and lines[-1] == '': lines.pop()
out = ['/* generated by tools/gen_default_ini.py from qoltweaks.ini - do not edit */', 'static const char QOL_DEFAULT_INI[] =']
for l in lines:
    out.append('    "' + l.replace('\\', '\\\\').replace('"', '\\"') + '\\r\\n"')
out[-1] += ';'
open(os.path.join(src, 'default_ini.h'), 'w', encoding='latin1', newline='\n').write('\n'.join(out) + '\n')
